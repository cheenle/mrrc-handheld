#!/usr/bin/env python3
"""Generate anti-aliased 8-bit-alpha bitmap fonts for the 240x240 panel.

The hand-written 5x7 font looked like a 1980s cash register; the ICOM HT
reference uses a smooth proportional face.  We bake DejaVu into C arrays.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
REG  = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

# (name, ttf, ptsize, first, last)
# Bold everywhere: on a 240x240 panel with no subpixel rendering, a regular
# weight at 11-14 px reads as grey mush.  Bold + the gamma-corrected blend in
# font_draw() is what makes small Chinese-labelled UI legible.
SETS = [
    ("font_big",   BOLD, 44, 0x2E, 0x39),   # . 0-9   -> the frequency readout
    ("font_mid",   BOLD, 19, 0x20, 0x7E),   # secondary values
    ("font_small", BOLD, 15, 0x20, 0x7E),   # every label
    ("font_tiny",  BOLD, 12, 0x20, 0x7E),   # frequency scale ticks
]


def build(ttf, size, first, last):
    f = ImageFont.truetype(ttf, size)
    ascent, descent = f.getmetrics()
    glyphs, pool = [], bytearray()
    for code in range(first, last + 1):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        img = Image.new("L", (adv + 8, ascent + descent + 4), 0)
        d = ImageDraw.Draw(img)
        d.text((2, 2), ch, font=f, fill=255)
        bbox = img.getbbox()
        if bbox is None:                     # space
            glyphs.append((0, 0, 0, 0, adv, len(pool)))
            continue
        x0, y0, x1, y1 = bbox
        crop = img.crop((x0, y0, x1, y1))
        w, h = crop.size
        glyphs.append((w, h, x0 - 2, y0 - 2, adv, len(pool)))
        pool += crop.tobytes()
    return glyphs, bytes(pool), ascent


def emit(out, name, glyphs, pool, first, last):
    out.append(f"static const glyph_t {name}_glyphs[] = {{")
    for w, h, bx, by, adv, off in glyphs:
        out.append(f"  {{{w},{h},{bx},{by},{adv},{off}}},")
    out.append("};")
    out.append(f"static const uint8_t {name}_pool[] = {{")
    for i in range(0, len(pool), 24):
        out.append("  " + ",".join(str(b) for b in pool[i:i + 24]) + ",")
    out.append("};")


out = ['/* AUTO-GENERATED by tools/gen_font.py — do not edit. */',
       '#include "ui_font.h"', ""]
decls = []
for name, ttf, size, first, last in SETS:
    glyphs, pool, ascent = build(ttf, size, first, last)
    emit(out, name, glyphs, pool, first, last)
    decls.append((name, first, last, ascent))
    print(f"{name}: {len(glyphs)} glyphs, pool {len(pool)} B", file=sys.stderr)

out.append("")
for name, first, last, ascent in decls:
    out.append(f"const font_t {name} = {{ {name}_glyphs, {name}_pool, "
               f"0x{first:02X}, 0x{last:02X}, {ascent} }};")

open("main/ui_fonts.c", "w").write("\n".join(out) + "\n")
print("wrote main/ui_fonts.c", file=sys.stderr)
